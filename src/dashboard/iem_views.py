"""Offline presentation of already-normalized IEM ASOS hourly observations.

This module does not fetch weather, compute fire scores, or import NFDRS4.
The input must be generated by src/data_processing/iem_hourly.py.
"""
from __future__ import annotations

from html import escape
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
from plotly.subplots import make_subplots

REQUIRED = {"station_id", "station_name", "time_utc", "source", "data_type",
            "report_count", "missing_hour", "temperature_f", "relative_humidity_pct",
            "wind_speed_mph", "precipitation_report_1h_in"}
MEASURES = ["temperature_f", "relative_humidity_pct", "wind_speed_mph",
            "precipitation_report_1h_in"]


def read_iem_hourly(path: Path) -> tuple[pd.DataFrame, str]:
    """Return clean station-hour rows, or empty frame when optional CSV is absent.

    A present but invalid file raises ValueError instead of silently plotting
    inaccurate observations. UTC timestamps are retained; California local
    labels are derived only for the chart presentation.
    """
    if not path.is_file():
        return pd.DataFrame(), (
            "No standardized IEM hourly CSV found. Generate it with "
            "python src/data_processing/iem_hourly.py --stations AAT BUR "
            "--start-date 2026-10-01 --end-date 2026-11-07"
        )
    try:
        d = pd.read_csv(path, low_memory=False)
    except (OSError, pd.errors.ParserError, UnicodeError) as exc:
        raise ValueError(f"Unable to read IEM hourly CSV: {exc}") from exc
    missing = REQUIRED - set(d.columns)
    if missing:
        raise ValueError("IEM hourly CSV missing columns: " + ", ".join(sorted(missing)))
    if d.empty:
        return d, "IEM hourly CSV is empty."
    if d[["station_id", "station_name", "time_utc", "source", "data_type"]].isna().any().any():
        raise ValueError("IEM hourly CSV has missing station, time or provenance information")
    d["station_id"] = d["station_id"].astype(str).str.strip()
    d["station_name"] = d["station_name"].astype(str).str.strip()
    if (d["station_id"] == "").any() or (d["station_name"] == "").any():
        raise ValueError("IEM hourly CSV has blank station metadata")
    if not d["source"].astype(str).eq("IEM ASOS archive").all():
        raise ValueError("IEM hourly CSV must identify the IEM ASOS archive")
    if not d["data_type"].astype(str).str.lower().eq("observed").all():
        raise ValueError("IEM hourly CSV contains records not labeled observed")
    d["timestamp_utc"] = pd.to_datetime(d["time_utc"], errors="coerce", utc=True)
    if d["timestamp_utc"].isna().any():
        raise ValueError("IEM hourly CSV contains invalid UTC timestamps")
    if not (d["timestamp_utc"] == d["timestamp_utc"].dt.floor("h")).all():
        raise ValueError("IEM hourly CSV timestamps must be on UTC hour boundaries")
    if d.duplicated(["station_id", "timestamp_utc"]).any():
        raise ValueError("IEM hourly CSV contains duplicate station-hours")
    for col in MEASURES + ["report_count"]:
        d[col] = pd.to_numeric(d[col], errors="coerce")
    if d["report_count"].isna().any() or (d["report_count"] < 0).any() or (d["report_count"] % 1 != 0).any():
        raise ValueError("IEM hourly CSV contains invalid report counts")
    # pandas round-trips Python booleans as True/False in CSV; do not use astype(bool).
    flags = d["missing_hour"].astype(str).str.strip().str.lower().map({"true": True, "false": False})
    if flags.isna().any():
        raise ValueError("IEM hourly CSV contains invalid missing_hour flags")
    d["missing_hour"] = flags.astype(bool)
    if not (d["missing_hour"] == d["report_count"].eq(0)).all():
        raise ValueError("IEM missing_hour flags disagree with report_count")
    if d.loc[d["missing_hour"], MEASURES].notna().any().any():
        raise ValueError("Missing station-hours must not contain imputed measurements")
    rh = d["relative_humidity_pct"].dropna()
    if not rh.between(0, 100).all():
        raise ValueError("Invalid IEM relative humidity outside 0–100%")
    for col in ["wind_speed_mph", "precipitation_report_1h_in"]:
        if (d[col].dropna() < 0).any():
            raise ValueError("Invalid negative IEM measurement: " + col)
    d["time_california"] = d["timestamp_utc"].dt.tz_convert("America/Los_Angeles")
    d = d.sort_values(["station_id", "timestamp_utc"]).reset_index(drop=True)
    stations = d["station_id"].nunique()
    reported = int((~d["missing_hour"]).sum())
    note = (f"Historical observed IEM ASOS data: {stations} station(s); "
            f"{reported:,}/{len(d):,} station-hours with reports. "
            "Saved CSV snapshot, not live conditions or wildfire danger.")
    return d, note


def summary_html(d: pd.DataFrame) -> str:
    rows = []
    for sid, group in d.groupby("station_id", sort=True):
        name = str(group["station_name"].iloc[0]); n = len(group)
        reported = int((~group["missing_hour"]).sum())
        missing = n - reported
        temp = int(group["temperature_f"].notna().sum())
        humid = int(group["relative_humidity_pct"].notna().sum())
        wind = int(group["wind_speed_mph"].notna().sum())
        rain = int(group["precipitation_report_1h_in"].notna().sum())
        rows.append(f"<tr><td><b>{escape(sid)}</b></td><td>{escape(name)}</td>"
                    f"<td>{reported:,}/{n:,}</td><td>{missing:,}</td>"
                    f"<td>{temp:,}</td><td>{humid:,}</td>"
                    f"<td>{wind:,}</td><td>{rain:,}</td></tr>")
    head = ("<thead><tr><th>ID</th><th>Station</th><th>Hours reported</th>"
            "<th>Missing hours</th><th>Temp available</th><th>RH available</th>"
            "<th>Wind available</th><th>Precip available</th></tr></thead>")
    return "<div class='scroll'><table>" + head + "<tbody>" + "".join(rows) + "</tbody></table></div>"


def station_charts(d: pd.DataFrame):
    """Two figures with two traces/station, keeping gaps as NaN."""
    stations = sorted(d["station_id"].unique().tolist())
    temp = make_subplots(specs=[[{"secondary_y": True}]])
    wind = make_subplots(specs=[[{"secondary_y": True}]])
    for i, sid in enumerate(stations):
        sub = d[d["station_id"] == sid]
        label = str(sub["station_name"].iloc[0])
        t = sub["time_california"]
        meta = f" · {sid} ({label})"
        temp.add_trace(go.Scatter(x=t, y=sub["temperature_f"], name="Temperature (°F)" + meta,
                    visible=(i == 0), mode="lines", connectgaps=False,
                    line=dict(color="#d06947",width=2)), secondary_y=False)
        temp.add_trace(go.Scatter(x=t, y=sub["relative_humidity_pct"], name="Humidity (%)" + meta,
                    visible=(i == 0), mode="lines", connectgaps=False,
                    line=dict(color="#2781a2",width=2)), secondary_y=True)
        wind.add_trace(go.Scatter(x=t,y=sub["wind_speed_mph"],name="Wind (mph)" + meta,
                    visible=(i == 0),mode="lines",connectgaps=False,
                    line=dict(color="#367f79",width=2)), secondary_y=False)
        # The IEM p01i hourly report may be rolling/overlapping, not a safe daily sum.
        wind.add_trace(go.Scatter(x=t,y=sub["precipitation_report_1h_in"],
                    name="IEM p01i report (in)" + meta,visible=(i == 0),mode="lines",
                    connectgaps=False,line=dict(color="#758bc1",width=1.5)), secondary_y=True)
    temp.update_layout(title="Observed station temperature and humidity · California local time")
    temp.update_yaxes(title_text="Temperature (°F)",secondary_y=False)
    temp.update_yaxes(title_text="Relative humidity (%)",range=[0,100],secondary_y=True,showgrid=False)
    wind.update_layout(title="Observed station wind and reported precipitation · California local time")
    wind.update_yaxes(title_text="Wind (mph)",secondary_y=False)
    wind.update_yaxes(title_text="IEM p01i (in)",secondary_y=True,showgrid=False)
    return temp, wind, stations
